// Builds the server-side answer key for the mini-game leaderboard from the
// game files, so the API can re-score runs without trusting the browser.
// Run after changing any minigames/*/game.js or catalog.js:
//   node scripts/build-minigames-key.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const gamesDir = join(root, "security-awareness-month", "minigames");
const out = join(root, "functions", "security-awareness-month", "_minigames-key.js");

function load(file) {
  const sandbox = { window: {} };
  vm.runInNewContext(readFileSync(file, "utf8"), sandbox, { filename: file });
  return sandbox.window;
}

const catalog = load(join(gamesDir, "catalog.js")).MINIGAMES;
const key = {};
for (const entry of catalog.games) {
  if (entry.pending) continue;
  const game = load(join(gamesDir, entry.id, "game.js")).GAME;
  if (game.id !== entry.id) throw new Error(`id mismatch: ${entry.id} vs ${game.id}`);
  const risks = game.spots.filter((s) => s.risk).map((s) => s.id);
  key[game.id] = {
    title: game.title,
    timeLimit: game.timeLimit || 600,
    minToContinue: game.minToContinue || Math.ceil(risks.length * 0.6),
    risks,
    chain: game.chain.map((q) => q.answer),
    options: game.chain.map((q) => q.options.length),
  };
}

const body = `// Generated by scripts/build-minigames-key.mjs from security-awareness-month/minigames. Do not edit.
export const GAMES = ${JSON.stringify(key, null, 2)};
`;
writeFileSync(out, body);
console.log(`Wrote ${Object.keys(key).length} games to ${out}`);
